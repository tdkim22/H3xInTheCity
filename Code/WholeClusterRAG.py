# Retrieval: aggregate feature statistics per cluster
# ============================================================

def aggregate_cluster_stats(
    df: pd.DataFrame,
    cluster_id: int,
    top_n: int = 10,
) -> tuple[pd.DataFrame, list[str], list[str]]:
    """
    Filter to the chosen cluster and compute per-feature stats:
      mean, max, presence_rate (fraction of hexes where feature > 0).

    Returns
    -------
    stats_df   : DataFrame with one row per feature, sorted by salience.
    top_feats  : feature names in the top_n by salience.
    absent     : feature names with presence_rate < 5%.
    """
    feature_cols = get_feature_columns(df)
    cluster_df = df[df["cluster_id"] == cluster_id]

    if cluster_df.empty:
        available = sorted(df["cluster_id"].unique().tolist())
        raise ValueError(
            f"Cluster ID {cluster_id} not found.\n"
            f"Available cluster IDs: {available}"
        )

    records = []
    for col in feature_cols:
        vals          = cluster_df[col].astype(float)
        mean_val      = float(vals.mean())
        max_val       = float(vals.max())
        presence_rate = float((vals > 0).mean())
        salience      = presence_rate * mean_val
        records.append({
            "feature":       col,
            "mean":          round(mean_val, 2),
            "max":           int(max_val),
            "presence_rate": round(presence_rate, 2),
            "salience":      round(salience, 4),
        })

    stats_df = (
        pd.DataFrame(records)
          .sort_values("salience", ascending=False)
          .reset_index(drop=True)
    )

    top_feats = stats_df.head(top_n)["feature"].tolist()
    absent    = stats_df[stats_df["presence_rate"] < 0.05]["feature"].tolist()

    return stats_df, top_feats, absent


# ============================================================
# Augmentation: building the context block
# ============================================================

def build_context_block(
    df: pd.DataFrame,
    cluster_id: int,
    stats_df: pd.DataFrame,
    top_feats: list[str],
    absent: list[str],
    top_n: int = 10,
) -> str:
    """
    Format retrieved statistics into a structured text block
    that will be injected into the LLM prompt.
    """
    cluster_df = df[df["cluster_id"] == cluster_id]
    hex_ids    = cluster_df["region_id"].tolist()
    top_stats  = stats_df[stats_df["feature"].isin(top_feats)].head(top_n)

    lines = [
        f"Cluster ID      : {cluster_id}",
        f"Hex count       : {len(cluster_df)}",
        f"Hex IDs         : {', '.join(hex_ids)}",
        "",
        f"Top {top_n} features by salience  (presence_rate × mean count):",
        f"  {'Feature':<24} {'Mean':>6}  {'Max':>5}  {'Presence':>9}",
        f"  {'-'*24} {'-'*6}  {'-'*5}  {'-'*9}",
    ]
    for _, row in top_stats.iterrows():
        lines.append(
            f"  {row['feature']:<24} {row['mean']:>6.2f}  "
            f"{row['max']:>5}  {row['presence_rate']*100:>8.0f}%"
        )

    if absent:
        lines += ["", f"Absent / rare features (<5% presence): {', '.join(absent)}"]

    return "\n".join(lines)


