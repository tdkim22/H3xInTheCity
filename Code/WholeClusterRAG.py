RESERVED_COLS = {"region_id", "cluster_id"}

def get_feature_columns(df: pd.DataFrame) -> list[str]:
    """
    Return all numeric columns that are not region_id or cluster_id.
    Raises clearly if required columns are missing.
    """
    missing = RESERVED_COLS - set(df.columns)
    if missing:
        raise ValueError(
            f"DataFrame is missing required column(s): {missing}\n"
            f"Expected columns: region_id, cluster_id, <feature columns...>"
        )

    feature_cols = [c for c in merged_df.columns if c not in {"region_id", "cluster_id"}]
    if not feature_cols:
        raise ValueError("No numeric feature columns found besides region_id / cluster_id.")
    merged_df[feature_cols] = merged_df[feature_cols].astype(float)
    return feature_cols

def list_clusters(df: pd.DataFrame) -> pd.DataFrame:
    """Print a summary table of all clusters in the DataFrame."""
    summary = (
        df.groupby('cluster_id')
          .agg(hex_count=("region_id", "count"))
          .reset_index()
    )
    print("Clusters in DataFrame:")
    print(summary.to_string(index=False))
    return summary

