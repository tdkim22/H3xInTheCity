# Generation: calling the Gemini API
# ============================================================

def describe_cluster(context_block: str, cluster_id: int) -> str:
    """Send the context block to Gemini and return the description."""
    prompt = (
        f"Please describe Cluster {cluster_id} based on the following "
        f"aggregated feature statistics retrieved from its member hexagons:\n\n"
        f"{context_block}"
    )
    response = CLIENT.generate_content(prompt)
    return response.text

# ============================================================
# Full RAG pipeline
# ============================================================

def run_rag_pipeline(
    df: pd.DataFrame,
    cluster_id: int,
    top_n: int = 10,
    verbose: bool = True,
) -> str:
    """
    End-to-end RAG pipeline.

    Parameters
    ----------
    df          : merged DataFrame with region_id, cluster_id, feature cols.
    cluster_id  : which cluster to describe.
    top_n       : number of top features to include in the context.
    verbose     : if True, print the context block before calling the API.

    Returns
    -------
    description : natural-language cluster description from Gemini.
    """
    # --- Retrieve ---
    stats_df, top_feats, absent = aggregate_cluster_stats(df, cluster_id, top_n)

    # --- Augment ---
    context_block = build_context_block(df, cluster_id, stats_df, top_feats, absent, top_n)

    if verbose:
        print("── Retrieved context block " + "─" * 34)
        #print(textwrap.fill(context_block, width=100))
        print(context_block)
        print("─" * 60 + "\n")

    # --- Generate ---
    print(f"Calling API for Cluster {cluster_id}…")
    description = describe_cluster(context_block, cluster_id)
    return description #AIzaSyAx0BosTIHANbLKHb-PCPRCRciL2w9c4_g

